#!/usr/bin/env python3
"""Writes src/concepts/autos/creditsData.ts and public/concepts/autos/CREDITS.md from photos-manifest.json,
variants.json and the files actually present in public/concepts/autos/variants/."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
man = json.load(open(os.path.join(HERE, "photos-manifest.json")))
cfg = json.load(open(os.path.join(HERE, "variants.json")))
ledger = json.load(open(os.path.join(HERE, "ledger.json")))
vdir = os.path.join(ROOT, "public/concepts/autos/variants")
NAMES = {"revuelto": "Lamborghini Revuelto", "huracan-sto": "Lamborghini Huracán STO", "911-gt3": "Porsche 911 GT3", "taycan-turbo": "Porsche Taycan Turbo S", "m4-csl": "BMW M4 CSL", "i5-m60": "BMW i5 M60"}
LIC = {"CC0": "https://creativecommons.org/publicdomain/zero/1.0/", "CC BY-SA 4.0": "https://creativecommons.org/licenses/by-sa/4.0/", "CC BY 4.0": "https://creativecommons.org/licenses/by/4.0/"}
entries = []
for k, e in man.items():
    entries.append(dict(model=e["model"], name=NAMES[e["model"]], angle=e["angle"], title=e["title"], author=e["author"], license=e["license"],
                        licenseUrl=e["license_url"] or LIC.get(e["license"], ""), source=e["source"]))
with open(os.path.join(ROOT, "src/concepts/autos/creditsData.ts"), "w") as f:
    f.write("// Generated by scripts/autos/build_credits.py. Do not edit by hand.\n")
    f.write("export interface PhotoCredit { model: string; name: string; angle: string; title: string; author: string; license: string; licenseUrl: string; source: string }\n\n")
    f.write("export const PHOTO_CREDITS: PhotoCredit[] = " + json.dumps(entries, indent=2, ensure_ascii=False) + "\n")

def nfiles(m): return sorted(x for x in os.listdir(os.path.join(vdir, m)) if x.endswith(".webp") and "-800" not in x) if os.path.isdir(os.path.join(vdir, m)) else []
md = ["# Credits and licences: Strada autos concept", "",
      "All car imagery on this concept is real photography from **Wikimedia Commons** (licences CC0, CC BY or CC BY-SA only), fetched through the Commons API. "
      "No manufacturer press images, no Google Images, no 3D models. The earlier procedural 3D cars were removed.", "",
      "Base photographs were cropped to 16:9, resized to 1600 px wide and converted to WebP (plus an 800 px copy). No other edits were made to them.", "",
      "## Base photographs", "",
      "| Model | Shot | Title | Author | Licence | Source |", "| --- | --- | --- | --- | --- | --- |"]
for e in entries:
    md.append(f"| {e['name']} | {e['angle']} | {e['title']} | {e['author']} | [{e['license']}]({e['licenseUrl']}) | [Commons file page]({e['source']}) |")
md += ["", "## AI-modified variants", "",
       f"Every image in `variants/` was produced by editing one of the base photographs above with Google Gemini image editing (model `{ledger['model']}`), "
       "changing only the paint colour or the wheels and keeping framing, background and car shape. "
       "**Each variant is modified with AI from the original credited below, and is shared under the same licence as its original** "
       "(CC BY-SA 4.0 share-alike applies; the CC0 original needs no attribution but is credited anyway). The as-photographed colour of each car is the unmodified photograph.", ""]
for m in cfg:
    fs = nfiles(m)
    base_front = man[f"{m}/front"]
    md.append(f"### {NAMES[m]}")
    md.append("")
    md.append(f"Modified with AI from *{base_front['title']}* by {base_front['author']} ({base_front['license']}), [source]({base_front['source']}).")
    if f"{m}/rear" in man and any("__rear" in x for x in fs):
        r = man[f"{m}/rear"]
        md.append(f"Rear-angle variants are modified with AI from *{r['title']}* by {r['author']} ({r['license']}), [source]({r['source']}).")
    md.append("")
    md.append("Files: " + ", ".join(f"`{x}`" for x in fs))
    md.append("")
md += ["## Generation record", "",
       f"- Image model: `{ledger['model']}` (the image model Content Studio is configured with).",
       f"- Calls made: {ledger['calls']} ({ledger['images_ok']} usable images, {ledger['failed']} failed).",
       f"- Estimated spend: ${ledger['estimated_cost_usd']:.2f} at ${ledger['price_per_image_usd']} per image, against a hard cap of ${ledger['cap_usd']:.2f}. See `scripts/autos/ledger.json`.", "",
       "## Other", "",
       "- Fonts: Archivo and Hanken Grotesk via `@fontsource-variable` (SIL Open Font License).",
       "- Brand names (Lamborghini, Porsche, BMW) and model names are used as text for a portfolio demonstration. No official logos or crests are used.",
       "- Prices are indicative and the dealer, Strada Motors, is fictional."]
open(os.path.join(ROOT, "public/concepts/autos/CREDITS.md"), "w").write("\n".join(md) + "\n")
print("ok", len(entries))
